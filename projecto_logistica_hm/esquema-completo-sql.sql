CREATE OR REPLACE FUNCTION public.notificar_observacion()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
    v_ejecutivo_id uuid;
    v_jefe_local_id uuid;
    v_logistica_id uuid;
BEGIN

    -- Obtener los participantes de la solicitud
    SELECT
        ejecutivo_id,
        jefe_local_id,
        logistica_id
    INTO
        v_ejecutivo_id,
        v_jefe_local_id,
        v_logistica_id
    FROM public.solicitud
    WHERE id = NEW.solicitud_id;

    ------------------------------------------------------------------
    -- Notificar al Ejecutivo
    ------------------------------------------------------------------
    IF v_ejecutivo_id IS NOT NULL
       AND v_ejecutivo_id <> NEW.usuario_id THEN

        INSERT INTO public.notificacion (
            usuario_id,
            emisor_id,
            tipo,
            titulo,
            mensaje,
            entidad,
            entidad_id,
            ruta
        )
        VALUES (
            v_ejecutivo_id,
            NEW.usuario_id,
            'NUEVA_OBSERVACION',
            'Nueva observación',
            'Se agregó una nueva observación en la solicitud.',
            'observacion',
            NEW.id,
            '/solicitudes/' || NEW.solicitud_id
        );

    END IF;

    ------------------------------------------------------------------
    -- Notificar al Jefe Local
    ------------------------------------------------------------------
    IF v_jefe_local_id IS NOT NULL
       AND v_jefe_local_id <> NEW.usuario_id THEN

        INSERT INTO public.notificacion (
            usuario_id,
            emisor_id,
            tipo,
            titulo,
            mensaje,
            entidad,
            entidad_id,
            ruta
        )
        VALUES (
            v_jefe_local_id,
            NEW.usuario_id,
            'NUEVA_OBSERVACION',
            'Nueva observación',
            'Se agregó una nueva observación en la solicitud.',
            'observacion',
            NEW.id,
            '/solicitudes/' || NEW.solicitud_id
        );

    END IF;

    ------------------------------------------------------------------
    -- Notificar a Logística
    ------------------------------------------------------------------
    IF v_logistica_id IS NOT NULL
       AND v_logistica_id <> NEW.usuario_id THEN

        INSERT INTO public.notificacion (
            usuario_id,
            emisor_id,
            tipo,
            titulo,
            mensaje,
            entidad,
            entidad_id,
            ruta
        )
        VALUES (
            v_logistica_id,
            NEW.usuario_id,
            'NUEVA_OBSERVACION',
            'Nueva observación',
            'Se agregó una nueva observación en la solicitud.',
            'observacion',
            NEW.id,
            '/solicitudes/' || NEW.solicitud_id
        );

    END IF;

    RETURN NEW;

END;
