                    'Vehículo entregado',
                    'El vehículo fue entregado.',
                    'solicitud',
                    NEW.id,
                    '/solicitudes/' || NEW.id
                );

            WHEN 'finalizada' THEN

                INSERT INTO public.notificacion (
                    usuario_id,
                    emisor_id,
                    tipo,
                    titulo,
                    mensaje,
                    entidad,
                    entidad_id,
                    ruta
                )
