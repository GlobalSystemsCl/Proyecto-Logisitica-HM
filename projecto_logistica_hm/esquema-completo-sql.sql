CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_nombre TEXT;
    v_apellido TEXT;
    v_rol TEXT;
BEGIN
    v_nombre := COALESCE(NEW.raw_user_meta_data->>'nombre', 'Usuario');
    v_apellido := COALESCE(NEW.raw_user_meta_data->>'apellido', '');
    v_rol := COALESCE(NEW.raw_user_meta_data->>'rol', 'ejecutivo');

    -- Si es el email del administrador principal, asegurar rol administrador
    IF LOWER(NEW.email) = 'maic.hernandez.dev@gmail.com' THEN
        v_rol := 'administrador';
    END IF;

    INSERT INTO public.usuario (
        id,
        email,
        nombre,
        apellido,
        rol,
        activo,
        requiere_cambio_clave
    )
    VALUES (
        NEW.id,
        NEW.email,
        v_nombre,
        v_apellido,
        v_rol,
        true,
        COALESCE((NEW.raw_user_meta_data->>'requiere_cambio_clave')::boolean, false)
    )
    ON CONFLICT (id) DO UPDATE SET
        email = EXCLUDED.email,
        nombre = CASE WHEN public.usuario.nombre = 'Usuario' THEN EXCLUDED.nombre ELSE public.usuario.nombre END,
        apellido = CASE WHEN public.usuario.apellido = '' THEN EXCLUDED.apellido ELSE public.usuario.apellido END,
        rol = CASE WHEN LOWER(EXCLUDED.email) = 'maic.hernandez.dev@gmail.com' THEN 'administrador' ELSE public.usuario.rol END,
        activo = true;

    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    -- Evitar que errores secundarios bloqueen auth.users
    RETURN NEW;
END;
$function$

CREATE OR REPLACE FUNCTION public.validate_solicitud_tipo()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
  IF NEW.tipo_solicitud = 'venta' THEN
    IF NEW.sucursal_destino IS NULL THEN
      RAISE EXCEPTION 'Una solicitud de tipo venta debe tener sucursal destino.';
    END IF;
  END IF;

  IF NEW.tipo_solicitud = 'evento' THEN
    IF NEW.direccion_evento IS NULL OR TRIM(NEW.direccion_evento) = '' THEN
      RAISE EXCEPTION 'Una solicitud de tipo evento debe tener direccion del evento.';
    END IF;
    IF NEW.titulo_evento IS NULL OR TRIM(NEW.titulo_evento) = '' THEN
      RAISE EXCEPTION 'Una solicitud de tipo evento debe tener titulo del evento.';
    END IF;
  END IF;

  RETURN NEW;
END;
$function$

CREATE OR REPLACE FUNCTION public.es_administrador()
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_rol TEXT;
    v_activo BOOLEAN;
BEGIN
    SELECT rol, activo INTO v_rol, v_activo
    FROM public.usuario
    WHERE id = auth.uid();

    RETURN (v_rol = 'administrador' AND COALESCE(v_activo, true) = true);
END;
$function$

CREATE OR REPLACE FUNCTION public.tiene_rol(VARIADIC roles text[])
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
    SELECT EXISTS (
        SELECT 1 FROM public.usuario
        WHERE id = auth.uid()
          AND COALESCE(activo, true) = true
          AND rol::text = ANY(roles)
    );
$function$

