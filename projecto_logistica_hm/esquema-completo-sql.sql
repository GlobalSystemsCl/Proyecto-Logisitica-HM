                    'solicitud',
                    NEW.id,
                    '/solicitudes/' || NEW.id
                );

            WHEN 'entregada' THEN

                INSERT INTO public.notificacion (
                    usuario_id,
                    emisor_id,
                    tipo,
                    titulo,
                    mensaje,
                    entidad,
                    entidad_id,
                    ruta
                )
                VALUES (
                    NEW.ejecutivo_id,
