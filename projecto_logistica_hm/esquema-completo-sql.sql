CREATE OR REPLACE FUNCTION public.notificar_solicitud_vehiculo()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
    v_ejecutivo_id uuid;
BEGIN

    -- Obtener el ejecutivo asociado a la solicitud
    SELECT ejecutivo_id
    INTO v_ejecutivo_id
    FROM public.solicitud
    WHERE id = NEW.solicitud_id;

    ------------------------------------------------------------------
    -- VEHÍCULO RESERVADO
    ------------------------------------------------------------------
    IF TG_OP = 'INSERT' THEN

        INSERT INTO public.notificacion (
            usuario_id,
            emisor_id,
            tipo,
            titulo,
            mensaje,
            entidad,
            entidad_id,
            ruta
        )
        VALUES (
            v_ejecutivo_id,
            auth.uid(),
            'VEHICULO_RESERVADO',
            'Vehículo reservado',
            'Se reservó un vehículo para tu solicitud.',
            'solicitud_vehiculo',
            NEW.id,
            '/solicitudes/' || NEW.solicitud_id
        );

        RETURN NEW;

    END IF;

    ------------------------------------------------------------------
    -- VEHÍCULO LIBERADO
    ------------------------------------------------------------------
    IF OLD.disponibilidad IS DISTINCT FROM NEW.disponibilidad THEN

        IF NEW.disponibilidad = 'liberado' THEN

            INSERT INTO public.notificacion (
                usuario_id,
                emisor_id,
                tipo,
                titulo,
                mensaje,
                entidad,
                entidad_id,
                ruta
            )
            VALUES (
                v_ejecutivo_id,
                auth.uid(),
                'VEHICULO_LIBERADO',
                'Vehículo liberado',
                'El vehículo asociado a tu solicitud fue liberado.',
                'solicitud_vehiculo',
                NEW.id,
                '/solicitudes/' || NEW.solicitud_id
            );

        END IF;

    END IF;

    RETURN NEW;

END;
$function$

CREATE OR REPLACE FUNCTION public.rls_auto_enable()
 RETURNS event_trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$

