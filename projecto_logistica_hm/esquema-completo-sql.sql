CREATE OR REPLACE FUNCTION public.auditoria_disponibilidad()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN

    -- Caso 1: Se asigna un vehículo nuevo a una solicitud
    IF TG_OP = 'INSERT' THEN

        INSERT INTO public.auditoria (
            usuario_id,
            entidad,
            entidad_id,
            accion,
            valor_anterior,
            valor_nuevo
        )
        VALUES (
            auth.uid(),
            'solicitud_vehiculo',
            NEW.id,
            'ASIGNACION_VEHICULO',
            NULL,
            jsonb_build_object(
                'solicitud_id', NEW.solicitud_id,
                'vehiculo_id', NEW.vehiculo_id,
                'disponibilidad', NEW.disponibilidad
            )
        );

        RETURN NEW;

    END IF;


    -- Caso 2: Cambia la disponibilidad del vehículo dentro de la solicitud
    IF TG_OP = 'UPDATE' 
       AND OLD.disponibilidad IS DISTINCT FROM NEW.disponibilidad THEN

        INSERT INTO public.auditoria (
            usuario_id,
            entidad,
            entidad_id,
            accion,
            valor_anterior,
            valor_nuevo
        )
        VALUES (
            auth.uid(),
            'solicitud_vehiculo',
            NEW.id,
            'CAMBIO_DISPONIBILIDAD_VEHICULO',
            jsonb_build_object(
                'disponibilidad', OLD.disponibilidad
            ),
            jsonb_build_object(
                'disponibilidad', NEW.disponibilidad
            )
        );

    END IF;


    RETURN NEW;

END;
$function$

